package com.whitelabel.buildlogic.apps

/** The Android emulator's alias for the host machine; the iOS simulator reaches the host as localhost. */
private const val ANDROID_EMULATOR_HOST = "10.0.2.2"

/**
 * The app's identity and API settings for one build type as an Xcode build-settings file. The
 * values are the ones Android publishes ([appConfigFields]), prefixed `WL_`, plus the bundle id
 * (with `.debug` for debug, as on Android) and the version. `//` is written as `/$()/`, since
 * xcconfig reads `//` as a comment. `WL_FIREBASE` is `on`, `fake` or `off` ([firebaseSetup], from the
 * build types that have a `GoogleService-Info.plist`, [firebaseConfigBuildTypes]);
 * `WL_ADMOB_APP_ID` is the iOS AdMob app ID ([resolvedAdmobAppId]; empty when absent), which Info.plist reads as
 * `GADApplicationIdentifier`. `WL_ADS` (`on`/`off`), `WL_ADS_UNITS` (`placement=unit;...`), `WL_ADS_TRACKING`
 * (`yes`/`no`) and `WL_ADS_TRACKING_MESSAGE` come from [adsSetup]; tracking and its message are published
 * only for a build type where ads are on. `WL_ADS_DECLARED` (`true`/`false`, the same in both build types)
 * says whether `ads.enabled` is set at all, so the app can tell a missing setting from a build type with
 * ads off (Android's `foundation_ads_declared`).
 */
internal fun iosXcconfig(app: AppConfig, buildType: String, firebaseConfigBuildTypes: Set<String> = emptySet()): String {
    val label = "apps/${app.appDir.name}"
    val firebase = firebaseSetup(
        app.firebase, firebaseConfigBuildTypes, adsAppId = app.adsIosAppId, adsAppIdKey = "ads.ios.appId",
        label = label, configFileName = "GoogleService-Info.plist",
    )
    val ads = adsSetup(app.ads, app.adsIosAppId, app.adsIosUnits, Platform.IOS, label)
    val adsOn = ads.modeFor.getValue(buildType) == "on"
    val tracking = adsOn && app.iosRequestTracking
    val fields = appConfigFields(app, buildType).toMutableMap()
    fields["API_BASE_URL"] = fields.getValue("API_BASE_URL").replace(ANDROID_EMULATOR_HOST, "localhost")
    val values = linkedMapOf(
        "BUNDLE_ID" to app.applicationId + if (buildType == "debug") ".debug" else "",
        "VERSION_NAME" to app.versionName,
        "VERSION_CODE" to app.versionCode.toString(),
    ) + fields +
        ("FIREBASE" to firebase.modeFor.getValue(buildType)) + ("ADMOB_APP_ID" to resolvedAdmobAppId(ads, app.adsIosAppId, buildType)) +
        ("ADS" to ads.modeFor.getValue(buildType)) +
        ("ADS_DECLARED" to ads.declared.toString()) +
        ("ADS_UNITS" to adsUnitsString(ads.unitsFor.getValue(buildType))) +
        ("ADS_TRACKING" to if (tracking) "yes" else "no") +
        ("ADS_TRACKING_MESSAGE" to if (tracking) app.iosTrackingMessage.orEmpty() else "")
    return buildString {
        appendLine("// Generated by generateIosConfig from ${app.appDir.name}/app.properties. Do not edit.")
        values.forEach { (key, value) -> appendLine("WL_$key = ${xcconfigValue(value)}") }
    }
}

/**
 * One xcconfig value on one line: line breaks and tabs become spaces, and every `//` (also in a run
 * such as `///`) is split as `/$()/`, since xcconfig reads `//` as a comment. The loader rejects
 * `$(...)` and `${...}` in the tracking message, which Xcode would expand.
 */
internal fun xcconfigValue(value: String): String =
    value.replace(Regex("[\\r\\n\\t]+"), " ").replace(Regex("/(?=/)")) { "/$()" }

/**
 * What an app's iOS framework (`Shared`) adds for consent, Firebase and ads. [modules] are added to
 * the framework and exported:
 * - every app: `:core:consent:shared`, `:core:firebase:shared` and `:core:ads:shared`. They are pure
 *   Kotlin (no Apple SDK), and WhitelabelKit's Swift names their types (`Consent` in
 *   `PrivacyChoicesRow`, `AdsController` and `AdPlacement` for banners), so the kit compiles only
 *   against a framework that exports them;
 * - an app with Firebase: also `:core:firebase:crashlytics`, the Kotlin crash hook over CrashKiOS,
 *   which the Swift `FirebaseService` calls.
 *
 * [crashLinkPlugin]: CrashKiOS' link plugin. An app without Firebase gets neither the hook nor the
 * plugin, so its framework holds no CrashKiOS code and links without Crashlytics.
 */
data class IosFirebaseFramework(val crashLinkPlugin: Boolean, val modules: List<String>)

private val EVERY_APP_MODULES = listOf(":core:consent:shared", ":core:firebase:shared", ":core:ads:shared")

fun iosFirebaseFramework(mode: ServiceMode): IosFirebaseFramework = when (mode) {
    ServiceMode.OFF -> IosFirebaseFramework(crashLinkPlugin = false, modules = EVERY_APP_MODULES)
    ServiceMode.ON, ServiceMode.DEBUG ->
        IosFirebaseFramework(crashLinkPlugin = true, modules = EVERY_APP_MODULES + ":core:firebase:crashlytics")
}
