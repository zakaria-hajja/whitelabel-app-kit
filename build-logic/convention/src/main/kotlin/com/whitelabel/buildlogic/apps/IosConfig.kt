package com.whitelabel.buildlogic.apps

/** The Android emulator's alias for the host machine; the iOS simulator reaches the host as localhost. */
private const val ANDROID_EMULATOR_HOST = "10.0.2.2"

/**
 * The app's identity and API settings for one build type as an Xcode build-settings file. The
 * values are the ones Android publishes ([appConfigFields]), prefixed `WL_`, plus the bundle id
 * (with `.debug` for debug, as on Android) and the version. `//` is written as `/$()/`, since
 * xcconfig reads `//` as a comment. `WL_FIREBASE` is `on`, `fake` or `off` ([firebaseSetup]);
 * `WL_ADMOB_APP_ID` is the iOS AdMob app ID (empty when absent), which Info.plist reads as `GADApplicationIdentifier`.
 */
internal fun iosXcconfig(app: AppConfig, buildType: String, firebaseConfigFileExists: Boolean = false): String {
    val firebase = firebaseSetup(
        app.firebase, firebaseConfigFileExists, adsAppId = app.adsIosAppId, adsAppIdKey = "ads.ios.appId",
        label = "apps/${app.appDir.name}", configFileName = "GoogleService-Info.plist",
    )
    val fields = appConfigFields(app, buildType).toMutableMap()
    fields["API_BASE_URL"] = fields.getValue("API_BASE_URL").replace(ANDROID_EMULATOR_HOST, "localhost")
    val values = linkedMapOf(
        "BUNDLE_ID" to app.applicationId + if (buildType == "debug") ".debug" else "",
        "VERSION_NAME" to app.versionName,
        "VERSION_CODE" to app.versionCode.toString(),
    ) + fields +
        ("FIREBASE" to firebase.modeFor.getValue(buildType)) + ("ADMOB_APP_ID" to app.adsIosAppId.orEmpty())
    return buildString {
        appendLine("// Generated by generateIosConfig from ${app.appDir.name}/app.properties. Do not edit.")
        values.forEach { (key, value) -> appendLine("WL_$key = ${value.replace("//", "/$()/")}") }
    }
}

/**
 * What an app's iOS framework (`Shared`) adds for consent and Firebase. [modules] are added to the
 * framework and exported:
 * - every app: `:core:consent:shared` and `:core:firebase:shared`. They are pure Kotlin (no Apple
 *   SDK), and WhitelabelKit's Swift names their types (`Consent` in `PrivacyChoicesRow`), so the kit
 *   compiles only against a framework that exports them;
 * - an app with Firebase: also `:core:firebase:crashlytics`, the Kotlin crash hook over CrashKiOS,
 *   which the Swift `FirebaseService` calls.
 *
 * [crashLinkPlugin]: CrashKiOS' link plugin. An app without Firebase gets neither the hook nor the
 * plugin, so its framework holds no CrashKiOS code and links without Crashlytics.
 */
data class IosFirebaseFramework(val crashLinkPlugin: Boolean, val modules: List<String>)

private val EVERY_APP_MODULES = listOf(":core:consent:shared", ":core:firebase:shared")

fun iosFirebaseFramework(mode: ServiceMode): IosFirebaseFramework = when (mode) {
    ServiceMode.OFF -> IosFirebaseFramework(crashLinkPlugin = false, modules = EVERY_APP_MODULES)
    ServiceMode.ON, ServiceMode.DEBUG ->
        IosFirebaseFramework(crashLinkPlugin = true, modules = EVERY_APP_MODULES + ":core:firebase:crashlytics")
}
